function seedSubStatus(orgId: string): Subscription["status"] {
  if (orgId === "t4" || orgId === "t9") return "trial";
  if (orgId === "t7") return "past_due";
  if (orgId === "t11") return "expired";
  if (orgId === "t14") return "cancelled";
  if (orgId === "t13") return "trial";
  return "active";
}

export const SEED_SUBSCRIPTIONS: Subscription[] = SEED_ORGANIZATIONS.map(
  (o, i) => {
    const plan = SEED_SAAS_PLANS.find((p) => p.id === o.planId)!;
    const status = seedSubStatus(o.id);
    return {
      id: `sub-${o.id}`,
      organizationId: o.id,
      planId: o.planId,
      status,
      billingCycle: plan.billingCycleDefault,
      startAt: o.createdAt,
      renewAt: o.renewalAt || o.trialEndsAt || o.createdAt,
      mrrSar: plan.priceMonthly,
      history: [
        {
          at: o.createdAt,
          text: `إنشاء اشتراك على خطة ${plan.name}`,
        },
        ...(i % 3 === 0
          ? [{ at: "2026-06-01T10:00:00.000Z", text: "تجديد سنوي" }]
          : []),
      ],
    };
  },
);

